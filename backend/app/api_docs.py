def patch_schema(schema):
    """把上面的说明补进生成好的 OpenAPI schema；没收录的接口保持原样。

    改生成结果而不是改路由对象：FastAPI 现在用 _IncludedRouter 包装
    include_router 进来的子路由，app.routes 里看到的不是真正的端点（既没有
    path 也没有 methods），在那一层贴说明会全部落空。改 schema 更稳，也不
    依赖框架的内部结构。
    """
    for path, operations in (schema.get("paths") or {}).items():
        for method, op in operations.items():
            doc = DOCS.get((method.upper(), path))
            if doc:
                op["summary"], op["description"] = doc
            if op.get("tags"):
                op["tags"] = [TAGS.get(t, t) for t in op["tags"]]
    return schema
